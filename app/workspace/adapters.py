"""Schema Adapter and Cursor Paging between MCP and REST protocols for Google Workspace."""
import base64
import json
from typing import Any, Optional, Tuple


class ProtocolCursorMismatchError(ValueError):
    """Raised when a pagination cursor encoded for one protocol is supplied to another."""
    pass


def encode_cursor(protocol: str, page_token: str) -> str:
    """Encode protocol and page token into a safe, opaque cursor string."""
    payload = {"p": protocol, "t": page_token}
    raw = json.dumps(payload, separators=(",", ":")).encode("utf-8")
    return base64.urlsafe_b64encode(raw).decode("utf-8")


def decode_cursor(cursor: str, expected_protocol: Optional[str] = None) -> Tuple[str, str]:
    """Decode cursor into (protocol, page_token).
    
    If expected_protocol is given and does not match the cursor's protocol,
    raises ProtocolCursorMismatchError.
    """
    try:
        raw = base64.urlsafe_b64decode(cursor.encode("utf-8")).decode("utf-8")
        data = json.loads(raw)
        protocol = data.get("p", "")
        page_token = data.get("t", "")
    except Exception as exc:
        raise ValueError(f"Invalid cursor format: {cursor}") from exc

    if expected_protocol and protocol != expected_protocol:
        raise ProtocolCursorMismatchError(
            f"Cursor protocol mismatch: cursor was generated by '{protocol}', but current request is using '{expected_protocol}'. "
            "Paging cannot be mixed between MCP and REST; please restart pagination."
        )

    return protocol, page_token


def normalize_workspace_result(
    protocol: str,
    service: str,
    operation: str,
    raw_data: Any,
) -> dict[str, Any]:
    """Normalize raw REST or MCP output into a unified dictionary structure.
    
    Returns:
        {
            "items": list[dict],
            "next_cursor": str | None,
            "protocol": "rest" | "mcp",
            "metadata": dict,
        }
    """
    if not isinstance(raw_data, dict):
        return {
            "items": raw_data if isinstance(raw_data, list) else [raw_data],
            "next_cursor": None,
            "protocol": protocol,
            "metadata": {},
        }

    items: list[dict[str, Any]] = []
    next_page_token: Optional[str] = None
    metadata: dict[str, Any] = {}

    # Extract next page token
    raw_token = raw_data.get("nextPageToken") or raw_data.get("next_page_token") or raw_data.get("pageToken")
    if raw_token:
        next_page_token = str(raw_token)

    # 1. Gmail normalization
    if service == "gmail":
        if "messages" in raw_data and isinstance(raw_data["messages"], list):
            for m in raw_data["messages"]:
                if not isinstance(m, dict):
                    continue
                # Extract headers if present
                headers_map: dict[str, str] = {}
                payload_obj = m.get("payload") or {}
                for h in payload_obj.get("headers", []):
                    name = h.get("name", "").lower()
                    headers_map[name] = h.get("value", "")

                items.append({
                    "id": m.get("id"),
                    "thread_id": m.get("threadId") or m.get("thread_id"),
                    "subject": headers_map.get("subject") or m.get("subject", "Không có tiêu đề"),
                    "from": headers_map.get("from") or m.get("from", ""),
                    "to": headers_map.get("to") or m.get("to", ""),
                    "date": headers_map.get("date") or m.get("date", ""),
                    "snippet": m.get("snippet", ""),
                })
        elif "drafts" in raw_data and isinstance(raw_data["drafts"], list):
            for d in raw_data["drafts"]:
                if not isinstance(d, dict):
                    continue
                msg = d.get("message") or {}
                items.append({
                    "id": d.get("id"),
                    "message": {
                        "id": msg.get("id"),
                        "thread_id": msg.get("threadId") or msg.get("thread_id"),
                        "snippet": msg.get("snippet", ""),
                    }
                })
        elif "id" in raw_data:
            items.append(raw_data)

    # 2. Calendar normalization
    elif service == "calendar":
        raw_items = raw_data.get("items") or raw_data.get("events") or []
        if isinstance(raw_items, list):
            for e in raw_items:
                if not isinstance(e, dict):
                    continue
                items.append({
                    "id": e.get("id"),
                    "summary": e.get("summary", "(Không có tiêu đề)"),
                    "start": e.get("start") or {},
                    "end": e.get("end") or {},
                    "html_link": e.get("htmlLink") or e.get("html_link") or "",
                    "status": e.get("status", "confirmed"),
                })
        elif "id" in raw_data:
            items.append({
                "id": raw_data.get("id"),
                "summary": raw_data.get("summary", ""),
                "start": raw_data.get("start") or {},
                "end": raw_data.get("end") or {},
                "html_link": raw_data.get("htmlLink") or raw_data.get("html_link") or "",
            })

    # 3. Drive normalization
    elif service == "drive":
        raw_files = raw_data.get("files") or raw_data.get("items") or []
        if isinstance(raw_files, list):
            for f in raw_files:
                if not isinstance(f, dict):
                    continue
                size_str = f.get("size") or f.get("size_bytes")
                try:
                    size_bytes = int(size_str) if size_str is not None else None
                except (ValueError, TypeError):
                    size_bytes = None

                items.append({
                    "id": f.get("id"),
                    "name": f.get("name") or f.get("title", ""),
                    "mime_type": f.get("mimeType") or f.get("mime_type", ""),
                    "size_bytes": size_bytes,
                    "modified_time": f.get("modifiedTime") or f.get("modified_time", ""),
                    "shared_drive_id": f.get("driveId") or f.get("shared_drive_id"),
                })
        elif "id" in raw_data:
            items.append(raw_data)

    # 4. Docs, Sheets, Slides or generic
    else:
        if "items" in raw_data and isinstance(raw_data["items"], list):
            items = raw_data["items"]
        else:
            items = [raw_data]

    next_cursor = encode_cursor(protocol, next_page_token) if next_page_token else None

    return {
        "items": items,
        "next_cursor": next_cursor,
        "protocol": protocol,
        "metadata": metadata,
    }

